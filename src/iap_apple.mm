// Apple StoreKit 2 backend for ge::iap (🎯T68 — replaces the earlier
// StoreKit 1 / SKPaymentQueue path from 🎯T65.2).
//
// Architecture:
//   * `iap_apple.swift` — `GEStoreKit2BridgeImpl` does the SK2 work
//     (Transaction.updates listener, Transaction.currentEntitlements
//     walk, Product.purchase, AppStore.sync). Pure Swift, async/await.
//     On-device JWS verification: only `.verified` transactions credit
//     entitlements; `.unverified` are logged and dropped.
//   * `iap_apple_bridge.h` — Obj-C protocols (`GEStoreKit2Bridge` +
//     `GEStoreKit2Listener`) so this file can talk to the Swift class
//     via typed `id<GEStoreKit2Bridge>` without importing the
//     autogenerated `<Target>-Swift.h`.
//   * `AppleStore` (this file) — implements `detail::Store`,
//     translates ge::iap's coarse API to Swift bridge calls, and
//     receives async callbacks through `GEStoreKit2ListenerImpl`.
//
// Bundle-ID prefixing (forward + reverse maps populated in setCatalogue)
// works the same as the SK1 path — Product::sku takes precedence when
// set, otherwise auto-prefix. Same T67 mechanic.
//
// macOS desktop: this file compiles to a single nullptr-returning
// `makePlatformStore()` so Module.mk builds (which include iap_apple.mm
// but don't compile the Swift bridge) link cleanly. The dispatcher in
// `iap.cpp` already defaults to stub on macOS, so the nullptr stub is
// the right behaviour — apps wanting Mac IAP would extend this path.

