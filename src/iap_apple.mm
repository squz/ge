namespace ge::iap::detail {

AppleStore::AppleStore() {
    // 🎯T65.5: prime the entitlement set from Keychain so owned() returns
    // the right answer on frame 0. The async StoreKit walk
    // (loadCurrentEntitlements below) reconciles when it completes —
    // additions land in the set, and the post-walk save will drop any
    // IDs that StoreKit no longer credits (revoked, refunded, etc.).
    entitled = loadKeychainEntitlements();
    if (!entitled.empty()) {
        SPDLOG_INFO("AppleStore: primed {} entitlements from Keychain cache", entitled.size());
    }

    // 🎯T65.4: GE_IAP_MODE=local uses SKTestSession via
    // GEStoreKit2LocalBridgeImpl; platform (the default) uses the
    // production GEStoreKit2BridgeImpl.
    const char* envMode = std::getenv("GE_IAP_MODE");
    const bool localMode = envMode && std::string(envMode) == "local";
    NSString* className = localMode
        ? @"GEStoreKit2LocalBridgeImpl"
        : @"GEStoreKit2BridgeImpl";

    Class implClass = NSClassFromString(className);
    if (!implClass && localMode) {
        // Local bridge not compiled in — fall back to production bridge.
        SPDLOG_WARN("AppleStore: GEStoreKit2LocalBridgeImpl not found — iap_apple_local.swift missing from build; falling back to production bridge");
        implClass = NSClassFromString(@"GEStoreKit2BridgeImpl");
    }
    if (!implClass) {
        SPDLOG_ERROR("AppleStore: GEStoreKit2BridgeImpl not found — Swift bridge missing from build");
        return;
    }
    bridge = (id<GEStoreKit2Bridge>)[[implClass alloc] init];
    GEStoreKit2ListenerImpl* l = [[GEStoreKit2ListenerImpl alloc] init];
    l.owner = this;
    listener = l;
    bridge.listener = l;
    [bridge start];
    [bridge loadCurrentEntitlements];
}

AppleStore::~AppleStore() {
    [bridge stop];
    if (listener) {
        ((GEStoreKit2ListenerImpl*)listener).owner = nullptr;
        listener = nil;
    }
    if (bridge) {
        bridge.listener = nil;
        bridge = nil;
    }
}

void AppleStore::setCatalogue(std::vector<Product> next) {
    NSMutableArray<NSString*>* skus = [NSMutableArray array];
    {
        std::lock_guard lock(mu);
        for (const auto& p : next) {
            catalogue.try_emplace(p.id, p);
            std::string platformId = platformSkuFor(p);
            platformSkuByLocal[p.id]       = platformId;
            localBySkuPlatform[platformId] = p.id;
            [skus addObject:[NSString stringWithUTF8String:platformId.c_str()]];
        }
    }
    [bridge fetchProducts:skus];
}

bool AppleStore::owned(const std::string& id) const {
    std::lock_guard lock(mu);
    return entitled.contains(id);
}

std::vector<LocalisedProduct> AppleStore::products() const {
    std::lock_guard lock(mu);
    std::vector<LocalisedProduct> out;
    out.reserve(localised.size());
    for (const auto& [id, lp] : localised) out.push_back(lp);
    return out;
}

void AppleStore::buy(const std::string& id, BuyCallback cb) {
    std::string platformId;
    {
        std::lock_guard lock(mu);
        auto it = platformSkuByLocal.find(id);
        if (it == platformSkuByLocal.end()) {
            Result r{.ok = false, .id = id, .error = "unknown product"};
            if (cb) cb(std::move(r));
            return;
        }
        platformId = it->second;
        pendingBuys[id] = std::move(cb);
    }
    [bridge purchase:[NSString stringWithUTF8String:platformId.c_str()]];
}

void AppleStore::restore(RestoreCallback cb) {
    {
        std::lock_guard lock(mu);
        pendingRestore = std::move(cb);
    }
    [bridge restore];
}

// ── Listener callbacks (called from Swift on the main thread) ──

void AppleStore::onProductFetched(const std::string& sku,
                                  const std::string& title,
                                  const std::string& description,
                                  const std::string& price,
                                  const std::string& currency) {
    std::lock_guard lock(mu);
    auto it = localBySkuPlatform.find(sku);
    if (it == localBySkuPlatform.end()) {
        SPDLOG_WARN("StoreKit 2 returned unmapped product identifier: {}", sku);
        return;
    }
    localised[it->second] = {
        .id          = it->second,
        .title       = title,
        .description = description,
        .price       = price,
        .currency    = currency,
    };
}

void AppleStore::onTransactionUpdate(const std::string& sku, bool ok, const std::string& error) {
    std::string localId;
    bool isConsumable = false;
    bool persist = false;
    std::unordered_set<std::string> snapshot;
    BuyCallback cb;
    {
        std::lock_guard lock(mu);
        auto skuIt = localBySkuPlatform.find(sku);
        if (skuIt == localBySkuPlatform.end()) {
            SPDLOG_WARN("Transaction update for unmapped product identifier: {}", sku);
            return;
        }
        localId = skuIt->second;
        auto pIt = catalogue.find(localId);
        if (pIt != catalogue.end()) isConsumable = pIt->second.type == Type::Consumable;
        if (ok && !isConsumable) {
            auto [_, inserted] = entitled.insert(localId);
            if (inserted) {
                persist = true;
                snapshot = entitled;  // copy under lock for off-lock write
            }
        }
        auto cbIt = pendingBuys.find(localId);
        if (cbIt != pendingBuys.end()) {
            cb = std::move(cbIt->second);
            pendingBuys.erase(cbIt);
        }
    }
    if (persist) saveKeychainEntitlements(snapshot);
    if (cb) cb({.ok = ok, .id = localId, .error = error});
}

void AppleStore::onCurrentEntitlement(const std::string& sku) {
    // Initial walk (silent auto-restore): credit non-consumables to the
    // cache. The reverse map may not yet contain this SKU if the
    // catalogue hasn't been registered — that's fine, the entitlement
    // just sits in StoreKit's records and we'll pick it up next launch
    // once the consumer calls setCatalogue.
    std::lock_guard lock(mu);
    auto it = localBySkuPlatform.find(sku);
    if (it == localBySkuPlatform.end()) {
        SPDLOG_INFO("StoreKit 2 currentEntitlements: unmapped {} — will pick up after setCatalogue", sku);
        return;
    }
    entitled.insert(it->second);
}

void AppleStore::onCurrentEntitlementsFinished() {
    // Phase marker — the entitlement cache is now populated for SKUs
    // we know about. 🎯T65.5: persist the reconciled set so the next
    // launch primes from Keychain with whatever StoreKit confirms now
    // (including any subset/superset changes vs. the Keychain prime).
    std::unordered_set<std::string> snapshot;
    {
        std::lock_guard lock(mu);
        snapshot = entitled;
    }
    saveKeychainEntitlements(snapshot);
    SPDLOG_INFO("AppleStore: currentEntitlements walk complete ({} entitled)", snapshot.size());
}

void AppleStore::onRestoreFinished(bool ok, const std::string& error) {
    RestoreCallback cb;
    std::unordered_set<std::string> snapshot;
    bool persist = false;
    {
        std::lock_guard lock(mu);
        cb = std::move(pendingRestore);
        pendingRestore = {};
        if (ok) {
            persist = true;
            snapshot = entitled;
        }
    }
    if (persist) saveKeychainEntitlements(snapshot);
    if (cb) cb({.ok = ok, .id = {}, .error = error});
}

std::unique_ptr<Store> makePlatformStore() {
    return std::make_unique<AppleStore>();
}

